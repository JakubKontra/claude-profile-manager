package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// docsCmd writes the command reference as Markdown (docs/cli, checked by
// CI) or as man pages (installed by Homebrew). It is hidden: it serves the
// build, not users.
func docsCmd() *cobra.Command {
	var markdown, man string
	cmd := &cobra.Command{
		Use:    "docs",
		Short:  "Generate the command reference (Markdown or man pages)",
		Hidden: true,
		Args:   cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if markdown == "" && man == "" {
				return fmt.Errorf("pass --markdown <dir> or --man <dir>")
			}
			root := cmd.Root()
			root.InitDefaultCompletionCmd()
			if markdown != "" {
				if err := writeDocs(root, markdown, ".md", renderMarkdown); err != nil {
					return err
				}
			}
			if man != "" {
				return writeDocs(root, man, ".1", renderMan)
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&markdown, "markdown", "", "write Markdown files to this directory")
	cmd.Flags().StringVar(&man, "man", "", "write man pages to this directory")
	return cmd
}

// documented lists the commands to document: everything but help and
// hidden commands, parents first, siblings by name.
func documented(c *cobra.Command) []*cobra.Command {
	if c.Hidden || c.Name() == "help" {
		return nil
	}
	// Cobra adds --help only when a command runs; add it now so usage lines
	// read the same whether docs are generated by `cpm docs` or a test.
	c.InitDefaultHelpFlag()
	list := []*cobra.Command{c}
	subs := c.Commands()
	sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
	for _, sub := range subs {
		list = append(list, documented(sub)...)
	}
	return list
}

// docName is the file name of c without extension: cpm, cpm-cloud-push.
func docName(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "-")
}

func writeDocs(root *cobra.Command, dir, ext string, render func(*cobra.Command) string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, c := range documented(root) {
		if err := os.WriteFile(filepath.Join(dir, docName(c)+ext), []byte(render(c)), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// flagLines lists flags as "--name type: usage (default x)". The user's home
// directory in defaults becomes ~, so the output is the same everywhere.
func flagLines(flags *pflag.FlagSet) []string {
	home, _ := os.UserHomeDir()
	var lines []string
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "--" + f.Name
		if f.Shorthand != "" {
			name = "-" + f.Shorthand + ", " + name
		}
		if t := f.Value.Type(); t != "bool" {
			name += " " + t
		}
		line := name + ": " + f.Usage
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" {
			def := f.DefValue
			if home != "" {
				def = strings.ReplaceAll(def, home, "~")
			}
			line += " (default " + def + ")"
		}
		lines = append(lines, line)
	})
	return lines
}

func description(c *cobra.Command) string {
	if c.Long != "" && !strings.Contains(c.Long, "_____") { // the root's banner
		return strings.TrimSpace(c.Long)
	}
	return c.Short + "."
}

func renderMarkdown(c *cobra.Command) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\n", c.CommandPath(), description(c))
	fmt.Fprintf(&b, "## Usage\n\n```\n%s\n```\n", c.UseLine())
	if lines := flagLines(c.LocalFlags()); len(lines) > 0 {
		b.WriteString("\n## Flags\n\n")
		for _, l := range lines {
			fmt.Fprintf(&b, "- %s\n", markdownFlag(l))
		}
	}
	if lines := flagLines(c.InheritedFlags()); len(lines) > 0 {
		b.WriteString("\n## Global flags\n\n")
		for _, l := range lines {
			fmt.Fprintf(&b, "- %s\n", markdownFlag(l))
		}
	}
	var subs []string
	for _, sub := range documented(c)[1:] {
		if sub.Parent() == c {
			subs = append(subs, fmt.Sprintf("- [%s](%s.md): %s", sub.CommandPath(), docName(sub), sub.Short))
		}
	}
	if len(subs) > 0 {
		b.WriteString("\n## Commands\n\n" + strings.Join(subs, "\n") + "\n")
	}
	if c.HasParent() {
		fmt.Fprintf(&b, "\nSee also [%s](%s.md).\n", c.Parent().CommandPath(), docName(c.Parent()))
	}
	return b.String()
}

// markdownFlag formats "--name type: usage" as "`--name type`: usage".
func markdownFlag(line string) string {
	name, usage, _ := strings.Cut(line, ": ")
	return "`" + name + "`: " + usage
}

// roff escapes text for a man page.
func roff(s string) string {
	s = strings.ReplaceAll(s, `\`, `\e`)
	s = strings.ReplaceAll(s, "-", `\-`)
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if strings.HasPrefix(l, ".") || strings.HasPrefix(l, "'") {
			lines[i] = `\&` + l
		}
	}
	return strings.Join(lines, "\n")
}

func renderMan(c *cobra.Command) string {
	var b strings.Builder
	name := docName(c)
	fmt.Fprintf(&b, ".TH %s 1 \"\" \"cpm\" \"cpm manual\"\n", strings.ToUpper(name))
	fmt.Fprintf(&b, ".SH NAME\n%s \\- %s\n", roff(name), roff(c.Short))
	fmt.Fprintf(&b, ".SH SYNOPSIS\n.nf\n%s\n.fi\n", roff(c.UseLine()))
	fmt.Fprintf(&b, ".SH DESCRIPTION\n%s\n", roff(description(c)))
	for _, section := range []struct {
		title string
		flags *pflag.FlagSet
	}{{"OPTIONS", c.LocalFlags()}, {"GLOBAL OPTIONS", c.InheritedFlags()}} {
		lines := flagLines(section.flags)
		if len(lines) == 0 {
			continue
		}
		fmt.Fprintf(&b, ".SH %s\n", section.title)
		for _, l := range lines {
			flag, usage, _ := strings.Cut(l, ": ")
			fmt.Fprintf(&b, ".TP\n.B %s\n%s\n", roff(flag), roff(usage))
		}
	}
	var see []string
	if c.HasParent() {
		see = append(see, docName(c.Parent())+"(1)")
	}
	for _, sub := range documented(c)[1:] {
		if sub.Parent() == c {
			see = append(see, docName(sub)+"(1)")
		}
	}
	if len(see) > 0 {
		fmt.Fprintf(&b, ".SH SEE ALSO\n%s\n", roff(strings.Join(see, ", ")))
	}
	return b.String()
}
