func findCheck(checks []Check, name string) (Check, bool) {
	for _, c := range checks {
		if c.Name == name {
			return c, true
		}
	}
	return Check{}, false
}

func noLookPath(string) (string, error) { return "", fmt.Errorf("not found") }

func TestRunDoctorHookAndGitChecks(t *testing.T) {
	t.Parallel()
	env := newTestEnv(t, twoProfiles+"\n[cloud]\nremote = \"x\"\n")
	home := t.TempDir()

	checks := RunDoctorWithOptions(env.load(t), env.profilesBase(), DoctorOptions{HomeDir: home, LookPath: noLookPath})
	if c, _ := findCheck(checks, "shell hook"); c.Status != "warn" {
		t.Errorf("hook should be missing: %+v", c)
	}
	if c, _ := findCheck(checks, "git binary"); c.Status != "error" {
		t.Errorf("git should be reported missing when cloud is configured: %+v", c)
	}

	mustWrite(t, filepath.Join(home, ".zshrc"), "eval \"$(cpm hook)\"\n")
	okLook := func(name string) (string, error) { return "/usr/bin/" + name, nil }
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), DoctorOptions{HomeDir: home, LookPath: okLook})
	if c, _ := findCheck(checks, "shell hook"); c.Status != "ok" || !strings.HasSuffix(c.Detail, ".zshrc") {
		t.Errorf("hook should be found: %+v", c)
	}
	if c, _ := findCheck(checks, "git binary"); c.Status != "ok" {
		t.Errorf("git should be ok: %+v", c)
	}

	// No cloud section: no git check.
	env2 := newTestEnv(t, twoProfiles)
	checks = RunDoctorWithOptions(env2.load(t), env2.profilesBase(), DoctorOptions{HomeDir: home, LookPath: noLookPath})
	if _, found := findCheck(checks, "git binary"); found {
		t.Error("git check must only run when cloud is configured")
	}
}

func TestRunDoctorUnknownKeys(t *testing.T) {
	t.Parallel()
	env := newTestEnv(t, "[profiles.work]\nmodl = \"x\"\n")
	checks := RunDoctorWithOptions(env.load(t), env.profilesBase(), DoctorOptions{HomeDir: t.TempDir(), LookPath: noLookPath})
	c, found := findCheck(checks, "config keys")
	if !found || c.Status != "warn" || !strings.Contains(c.Detail, "profiles.work.modl") {
		t.Errorf("unknown key not reported: %+v", c)
	}
}

func TestRunDoctorWrapperOutdated(t *testing.T) {
	t.Parallel()
	env := newTestEnv(t, twoProfiles)
	app := env.App
	if err := app.InstallProfiles(env.load(t), InstallOptions{}); err != nil {
		t.Fatal(err)
	}
	opts := DoctorOptions{HomeDir: t.TempDir(), LookPath: noLookPath}
	checks := RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/wrapper"); c.Status != "ok" {
		t.Errorf("fresh wrapper should be ok: %+v", c)
	}

	mustWrite(t, filepath.Join(env.BinDir, "claude-work"), "#!/bin/bash\n# Generated by cpm (Claude Profile Manager)\nexec claude\n")
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/wrapper"); c.Status != "warn" || !strings.Contains(c.Detail, "outdated") {
		t.Errorf("stale wrapper not detected: %+v", c)
	}
	os.Remove(filepath.Join(env.BinDir, "claude-work"))
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/wrapper"); !strings.Contains(c.Detail, "missing") {
		t.Errorf("missing wrapper not detected: %+v", c)
	}
}

func TestRunDoctorVerifyKeychain(t *testing.T) {
	t.Parallel()
	env := newTestEnv(t, "[profiles.work]\n")
	profileDir := filepath.Join(env.profilesBase(), "work")
	mustMkdir(t, profileDir)
	token := func(expires time.Time) string {
		return fmt.Sprintf(`{"claudeAiOauth":{"expiresAt":%d,"subscriptionType":"max"}}`, expires.UnixMilli())
	}
	env.Keychain.login(profileDir, token(time.Now().Add(-time.Hour)))
	opts := DoctorOptions{HomeDir: t.TempDir(), LookPath: noLookPath, Keychain: env.Keychain}

	checks := RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/credentials"); c.Status != "ok" {
		t.Errorf("without --verify the keychain login is ok: %+v", c)
	}

	opts.Verify = true
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/credentials"); c.Status != "warn" || !strings.Contains(c.Detail, "expired") {
		t.Errorf("--verify should report the expired token: %+v", c)
	}

	env.Keychain.login(profileDir, token(time.Now().Add(time.Hour)))
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/credentials"); c.Status != "ok" || !strings.Contains(c.Detail, "(max)") || !strings.Contains(c.Detail, "valid until") {
		t.Errorf("--verify should show subscription and expiry: %+v", c)
	}

	// Read failure keeps the plain status.
	env.Keychain.readErr = fmt.Errorf("denied")
	checks = RunDoctorWithOptions(env.load(t), env.profilesBase(), opts)
	if c, _ := findCheck(checks, "profile/work/credentials"); c.Status != "ok" {
		t.Errorf("read failure must not fail the check: %+v", c)
	}
}

func TestDoctorFix(t *testing.T) {
	t.Parallel()
	env := newTestEnv(t, "[profiles.work]\n[profiles.home]\n")
	mustWrite(t, filepath.Join(env.SourceDir, "settings.json"), `{}`)
	mustMkdir(t, filepath.Join(env.SourceDir, "skills"))
	if err := env.App.InstallProfiles(env.load(t), InstallOptions{}); err != nil {
		t.Fatal(err)
	}
	// Break things install can repair: a deleted wrapper, a broken
	// symlink into the source dir and a profile that was never installed.
	os.Remove(filepath.Join(env.BinDir, "claude-work"))
	link := filepath.Join(env.profilesBase(), "work", "skills")
	os.Remove(link)
	if err := os.Symlink(filepath.Join(env.Root, "gone"), link); err != nil {
		t.Fatal(err)
	}
	writeTestConfig(t, env, "[profiles.work]\n[profiles.home]\n[profiles.new]\n")
	opts := DoctorOptions{LookPath: noLookPath}

	before := env.App.DoctorReportFor(env.load(t), opts)
	for _, name := range []string{"profile/work/wrapper", "profile/work/skills", "profile/new"} {
		if c, ok := findCheck(before.Checks, name); !ok || c.Status == "ok" || c.Fix != installFix {
			t.Errorf("%s before: %+v", name, c)
		}
	}
	if c, _ := findCheck(before.Checks, "profile/home/credentials"); c.Fix != "cpm login home" {
		t.Errorf("credentials hint: %+v", c)
	}

	after, err := env.App.DoctorFix(env.load(t), opts)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range after.Checks {
		if c.Status != "ok" && c.Fix == installFix {
			t.Errorf("not fixed: %+v", c)
		}
	}
	if !fileExists(filepath.Join(env.BinDir, "claude-work")) || !fileExists(filepath.Join(env.profilesBase(), "new")) {
		t.Error("wrapper or profile not restored")
	}
	if !strings.Contains(env.Out.String(), "Fixing 3 checks with cpm install") {
		t.Errorf("output:\n%s", env.Out.String())
	}

	// Nothing to fix: no install runs.
	env.Out.Reset()
	if _, err := env.App.DoctorFix(env.load(t), opts); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(env.Out.String(), "Fixing") {
		t.Errorf("second fix ran install:\n%s", env.Out.String())
	}
}
